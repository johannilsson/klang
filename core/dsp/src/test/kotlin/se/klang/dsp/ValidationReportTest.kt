package se.klang.dsp

import java.io.File
import java.util.Locale
import kotlin.test.Test

/**
 * Not an assertion test: regenerates docs/validation-synthetic.md with the current algorithm, so the
 * documented synthetic numbers always come from code. Run: ./gradlew -p core :dsp:test -Dklang.writeReport=true
 */
class ValidationReportTest {
    /**
     * Realisations per cell. A noise realisation of a short, narrow-band decay scatters by ~12 %
     * (250 Hz, T60 = 0.3 s), so 10 seeds gave a mean 1.6 standard errors off (issue #11).
     */
    private val seeds = 50

    @Test
    fun writeReport() {
        if (System.getProperty("klang.writeReport") != "true") return
        val bands = listOf(250, 500, 1000, 2000, 4000)
        val analyzer = DecayAnalyzer()
        val sb = StringBuilder()
        sb.appendLine("# Synthetic validation results")
        sb.appendLine()
        sb.appendLine("Generated by `ValidationReportTest` with algorithm `${AnalysisConfiguration.ALGORITHM_ID}` ${AnalysisConfiguration.VERSION}, 48 kHz, background −90 dBFS RMS, $seeds seeds per row.")
        sb.appendLine("Values are T20 / true T60: mean ± standard deviation of single realisations (min–max). Synthetic engineering checks only — not a real-room accuracy claim.")
        sb.appendLine()
        for (exc in SyntheticImpulse.Excitation.entries) {
            sb.appendLine("## ${exc.name}")
            sb.appendLine()
            sb.appendLine("| T60 [s] | " + bands.joinToString(" | ") { "$it Hz mean ± SD (min–max)" } + " | valid / questionable / invalid |")
            sb.appendLine("|---|" + bands.joinToString("") { "---|" } + "---|")
            for (t in listOf(0.3, 0.5, 0.8, 1.2)) {
                val ratios = bands.associateWith { mutableListOf<Double>() }
                var v = 0; var q = 0; var inv = 0
                for (seed in 1L..seeds.toLong()) {
                    val spec = SyntheticImpulse.Spec(excitation = exc, decaySeconds = bands.associateWith { t }, durationSeconds = 0.75 + 2.5 * t + 0.6, seed = seed)
                    val r = analyzer.analyze(SyntheticImpulse.generate(spec))
                    r.bands.forEach { b ->
                        when (b.state) { QualityState.VALID -> v++; QualityState.QUESTIONABLE -> q++; QualityState.INVALID -> inv++ }
                        b.t20?.let { ratios[b.centerHz]!! += it.seconds / t }
                    }
                }
                sb.appendLine("| $t | " + bands.joinToString(" | ") { fc ->
                    val l = ratios[fc]!!
                    if (l.isEmpty()) "—" else String.format(Locale.ROOT, "%.3f ± %.3f (%.3f–%.3f)", l.average(), sd(l), l.min(), l.max())
                } + " | $v / $q / $inv |")
            }
            sb.appendLine()
        }
        File(System.getProperty("klang.reportPath", "../../docs/validation-synthetic.md")).writeText(sb.toString())
    }

    /** Sample standard deviation (n − 1). */
    private fun sd(l: List<Double>): Double {
        if (l.size < 2) return 0.0
        val m = l.average()
        return kotlin.math.sqrt(l.sumOf { (it - m) * (it - m) } / (l.size - 1))
    }
}
