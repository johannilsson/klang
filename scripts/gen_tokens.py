#!/usr/bin/env python3
"""Generate the app's colours and a CSS file for prototypes from design/tokens.json.

  scripts/gen_tokens.py          write app/.../theme/Color.kt and design/tokens.css
  scripts/gen_tokens.py --check  exit 1 if the generated files are out of date (CI)
"""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / "design/tokens.json"
KOTLIN = ROOT / "app/src/main/java/se/klang/app/ui/theme/Color.kt"
CSS = ROOT / "design/tokens.css"


def walk(node, path=()):
    """Yield (path, value, description) for every token; groups carry an optional $description."""
    if "$value" in node:
        yield path, node["$value"], node.get("$description", "")
        return
    for key, child in node.items():
        if not key.startswith("$"):
            yield from walk(child, path + (key,))


def groups(root):
    """(group name, description, tokens) for each direct child group of color."""
    for name, g in root["color"].items():
        if not name.startswith("$"):
            yield name, g.get("$description", ""), list(walk(g))


def argb(hex_):
    assert re.fullmatch(r"#[0-9A-Fa-f]{6}", hex_), f"colour must be #RRGGBB: {hex_}"
    return "0xFF" + hex_[1:].upper()


def kotlin_name(path):
    # seed/primary/40 -> Primary40, data/baseline -> BaselineColor
    return (path[0].capitalize() + path[1]) if path[-1].isdigit() else path[-1].capitalize() + "Color"


def make_kotlin(root):
    out = ["// Generated by scripts/gen_tokens.py from design/tokens.json. Do not edit by hand.",
           "package se.klang.app.ui.theme", "", "import androidx.compose.ui.graphics.Color"]
    for _, desc, toks in groups(root):
        out.append("")
        if desc:
            out.append(f"/** {desc} */")
        for path, value, _ in toks:
            out.append(f"val {kotlin_name(path)} = Color({argb(value)})")
    return "\n".join(out) + "\n"


def make_css(root):
    out = ["/* Generated by scripts/gen_tokens.py from design/tokens.json. Do not edit by hand. */", ":root {"]
    for gname, desc, toks in groups(root):
        if desc:
            out.append(f"  /* {desc} */")
        for path, value, _ in toks:
            out.append(f"  --klang-{gname}-{'-'.join(path)}: {value.lower()};")
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    root = json.loads(TOKENS.read_text())
    files = {KOTLIN: make_kotlin(root), CSS: make_css(root)}
    if "--check" in sys.argv:
        stale = [str(p.relative_to(ROOT)) for p, text in files.items() if not p.exists() or p.read_text() != text]
        if stale:
            print("Out of date, run scripts/gen_tokens.py:", ", ".join(stale))
            sys.exit(1)
        print("Generated token files are up to date")
        return
    for p, text in files.items():
        p.write_text(text)
        print("wrote", p.relative_to(ROOT))


main()
